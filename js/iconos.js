/**
 * Devuelve el texto SVG de un icono.
 * @param {string} nombre - Clave del icono, por ejemplo "mail".
 * @returns {string} Código SVG listo para insertar en el HTML.
 */
function icono(nombre) {
  if (nombre === "google") return ICONO_GOOGLE;
  const dibujo = ICONOS[nombre] || "";
  return (
    '<svg class="icono" viewBox="0 0 24 24" fill="none" stroke="currentColor" ' +
    'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
    dibujo +
    "</svg>"
  );
}

/**
 * Busca en la página todos los elementos con data-icono y les inserta el dibujo.
 * Se puede llamar varias veces: cada elemento se procesa una sola vez.
 */
function pintarIconos() {
  document.querySelectorAll("[data-icono]").forEach(function (elemento) {
    elemento.innerHTML = icono(elemento.dataset.icono);
    elemento.removeAttribute("data-icono"); // ya está pintado
  });
}

// Pinta los iconos apenas el HTML termine de cargar
document.addEventListener("DOMContentLoaded", pintarIconos);
